#!/usr/bin/env python3
"""Generate a deterministic Markdown index from preserved analysis CSV files."""

from __future__ import annotations

import argparse
import csv
import hashlib
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    "functions": Path("analysis/memory/function_ranges.csv"),
    "globals": Path("analysis/memory/globals.csv"),
    "active_irqs": Path("analysis/interrupts/active_irqs.csv"),
    "handler_renames": Path("analysis/interrupts/verified_handler_renames.csv"),
    "hardware_resources": Path("analysis/hardware/hardware_resources.csv"),
    "peripheral_coverage": Path(
        "analysis/hardware/peripheral_access_coverage.csv"
    ),
    "control_registers": Path("analysis/protocol/control_register_audit.csv"),
    "base_update": Path("analysis/linux_app/base_update_sequence.csv"),
    "xmodem": Path("analysis/linux_app/xmodem_1k_contract.csv"),
}


def read_csv(relative: Path) -> list[dict[str, str]]:
    with (ROOT / relative).open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def sha256(relative: Path) -> str:
    return hashlib.sha256((ROOT / relative).read_bytes()).hexdigest()


def md(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def link(relative: Path) -> str:
    return f"[`{relative.name}`](../{relative.as_posix()})"


def table(headers: list[str], rows: list[list[object]]) -> list[str]:
    result = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    result.extend("| " + " | ".join(md(cell) for cell in row) + " |" for row in rows)
    return result


def generate() -> str:
    functions = read_csv(SOURCES["functions"])
    globals_ = read_csv(SOURCES["globals"])
    active_irqs = read_csv(SOURCES["active_irqs"])
    renames = read_csv(SOURCES["handler_renames"])
    hardware = read_csv(SOURCES["hardware_resources"])
    peripheral = read_csv(SOURCES["peripheral_coverage"])
    controls = read_csv(SOURCES["control_registers"])
    base_update = read_csv(SOURCES["base_update"])
    xmodem = read_csv(SOURCES["xmodem"])

    global_blocks = Counter(row["block"] for row in globals_)
    hardware_categories = Counter(row["category"] for row in hardware)
    control_statuses = Counter(row["BASE_1.1.9_status"] for row in controls)
    rename_by_address = {
        row["address"].lower(): row["new_name"] for row in renames
    }
    peripheral_values = {row["metric"]: row["value"] for row in peripheral}

    lines = [
        "# Generated analysis summary",
        "",
        "> Generated by `tools/generate_analysis_markdown.py`. Do not edit this",
        "> file manually. The source CSV/TXT exports are preserved unchanged.",
        "",
        "## Snapshot",
        "",
    ]
    lines += table(
        ["Metric", "Value", "Evidence"],
        [
            ["Recovered functions", len(functions), "Ghidra function bodies"],
            ["Global data labels", len(globals_), "exact-address Ghidra data labels"],
            ["Active external IRQs", len(active_irqs), "vector table"],
            ["VERIFIED handler names", len(renames), "CSV rename set"],
            ["Hardware-resource records", len(hardware), "software-visible contracts"],
            [
                "Peripheral instruction references",
                peripheral_values["exported_references"],
                "Ghidra data references",
            ],
            [
                "Peripheral target addresses",
                peripheral_values["exact_target_addresses"],
                "exact recovered targets",
            ],
            ["Control-register slots", len(controls), "complete 56-word window"],
            ["Linux BASE-update phases", len(base_update), "unstripped Linux ELF"],
            ["XMODEM contract rows", len(xmodem), "unstripped Linux ELF"],
        ],
    )

    lines += ["", "## Memory-label distribution", ""]
    lines += table(
        ["Ghidra block", "Data labels"],
        [[name, count] for name, count in sorted(global_blocks.items())],
    )
    lines += [
        "",
        "These are exported Ghidra labels, not automatically recovered C",
        "variables. The apparent CCMRAM labels are known false-positive address",
        "constants; see [`memory_map.md`](memory_map.md).",
    ]

    lines += ["", "## Active interrupt handlers", ""]
    irq_rows = []
    for row in active_irqs:
        address = row["code_address"].lower()
        if address.startswith("0x"):
            address = address[2:]
        irq_rows.append(
            [
                row["irq"],
                row["standard_name"],
                f"`{row['code_address']}`",
                f"`{rename_by_address.get(address, row['current_name'])}`",
                "VERIFIED",
            ]
        )
    lines += table(
        ["IRQ", "Vector", "Address", "Persistent name", "Confidence"], irq_rows
    )
    lines += [
        "",
        f"`Default_Handler` at `0x{renames[0]['address'].upper()}` is also in the",
        "VERIFIED rename set.",
    ]

    lines += ["", "## Peripheral-reference coverage", ""]
    lines += table(
        ["Metric", "Value", "Confidence"],
        [
            [row["metric"], row["value"], row["confidence"]]
            for row in peripheral
        ],
    )
    lines += [
        "",
        "`READ` and `WRITE` are direct accesses. Address/parameter references",
        "are retained separately and are not by themselves register transactions.",
    ]

    lines += ["", "## Software-visible resource inventory", ""]
    lines += table(
        ["Category", "Records"],
        [[name, count] for name, count in sorted(hardware_categories.items())],
    )
    lines += [
        "",
        "The complete resource contracts, pins, addresses, lifecycle, and",
        "confidence assignments remain in "
        f"{link(SOURCES['hardware_resources'])} and",
        "[`hardware_map.md`](hardware_map.md).",
    ]

    lines += ["", "## Control-register audit", ""]
    lines += table(
        ["BASE 1.1.9 status", "Slots"],
        [[name, count] for name, count in sorted(control_statuses.items())],
    )
    exceptional = [row for row in controls if row["BASE_1.1.9_status"] != "active"]
    lines += ["", "### Slots not classified simply as active", ""]
    lines += table(
        ["Index", "Historical label", "Status", "Recovered effect", "Confidence"],
        [
            [
                row["index"],
                row["historical_label"],
                row["BASE_1.1.9_status"],
                row["effect"],
                row["confidence"],
            ]
            for row in exceptional
        ],
    )

    lines += ["", "## Source manifest", ""]
    lines += table(
        ["Input", "SHA-256"],
        [[link(relative), f"`{sha256(relative)}`"] for relative in SOURCES.values()],
    )
    lines += [
        "",
        "Generation reads these files and writes only this Markdown output.",
        "No source analysis artifact is rewritten or deleted.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "output",
        nargs="?",
        default="docs/generated_analysis_summary.md",
        help="output path relative to the repository root",
    )
    args = parser.parse_args()
    output = (ROOT / args.output).resolve()
    if ROOT not in output.parents:
        raise SystemExit("output must be inside the repository")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
